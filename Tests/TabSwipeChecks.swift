var swipe = TabSwipeAccumulator()
precondition(!MorisTaskFeature.isEnabled && !tabs.contains { $0.view == .tasks }, "Held Tasks must not appear in click or swipe navigation")
precondition(swipe.update(dx: -25, dy: 1, threshold: 70) == nil)
precondition(swipe.update(dx: -46, dy: 2, threshold: 70) == 1)
precondition(swipe.claimed)
precondition(swipe.update(dx: -200, dy: 0, threshold: 70) == nil, "Only one tab per gesture")
swipe.reset()
precondition(swipe.update(dx: 75, dy: 2, threshold: 70) == -1)
swipe.reset()
precondition(swipe.update(dx: 2, dy: 20, threshold: 70) == nil)
precondition(swipe.update(dx: 200, dy: 0, threshold: 70) == nil, "Vertical gesture must remain scrolling")
precondition(!swipe.claimed)
swipe.reset()
precondition(swipe.update(dx: 60, dy: 55, threshold: 70) == nil)
precondition(swipe.update(dx: 20, dy: 10, threshold: 70) == nil, "Diagonal scroll must not switch tabs")
swipe.reset()
precondition(swipe.update(dx: -40, dy: 0, threshold: 70) == nil)
precondition(swipe.update(dx: 40, dy: 0, threshold: 70) == nil, "Opposite movements cancel")
precondition(swipe.update(dx: 80, dy: 0, threshold: 70) == -1)
print("PASS: directional tab swipes, thresholds, one switch per gesture, vertical lock, diagonal rejection and reset")
